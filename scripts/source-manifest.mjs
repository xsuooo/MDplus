import { createHash } from 'node:crypto';
import childProcess from 'node:child_process';
import { constants } from 'node:fs';
import fs from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

// This is an observed-input binding, not an atomic snapshot or a build signature.
const POLICY = 'mdplus-source-v1';
const SOURCE_DIRECTORIES = new Set([
  'src',
  'public',
  'src-tauri',
  'tests',
  'scripts',
  'config',
  '.github',
]);
const ROOT_FILES = new Set([
  'package.json',
  'package-lock.json',
  'npm-shrinkwrap.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  'bun.lock',
  'bun.lockb',
  'index.html',
  '.gitignore',
  '.gitattributes',
  '.node-version',
  '.nvmrc',
  'rust-toolchain',
  'rust-toolchain.toml',
  '.prettierrc.json',
  '.prettierignore',
  '.editorconfig',
]);
const EXCLUDED_NAMES = new Set([
  '.git',
  '.audit',
  'node_modules',
  'target',
  'dist',
  'dist-ssr',
  'coverage',
  '.vite',
  '.cache',
  '__pycache__',
  'test-results',
  'playwright-report',
  'blob-report',
  'logs',
  'profiles',
  'profile',
  'user-profile',
  '.vscode',
  '.idea',
  '.claude',
  '.workbuddy',
  '.dsh',
  '.ssh',
  '.aws',
  '.azure',
  '.npmrc',
  '.yarnrc',
  '.yarnrc.yml',
  '.pypirc',
  'credentials',
  'secrets',
  'local.settings.json',
]);
const comparePaths = (a, b) => Buffer.compare(Buffer.from(a, 'utf8'), Buffer.from(b, 'utf8'));
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

function selected(path) {
  const lower = path.toLowerCase();
  const parts = lower.split('/');
  if (
    parts.some(
      (part) =>
        EXCLUDED_NAMES.has(part) ||
        /^\.env(?:\.|$)/.test(part) ||
        /^(?:credentials|secrets|id_rsa|id_ed25519)(?:\.|$)/.test(part) ||
        /(?:\.local(?:\.|$)|\.(?:pem|key|pfx|p12|keystore|jks|log|tmp|partial|bak|swp|pyc|tsbuildinfo|exe|dll|pdb|msi|msix|zip|7z)$)/.test(
          part,
        ),
    )
  )
    return false;
  if (lower === 'src-tauri/gen/schemas' || lower.startsWith('src-tauri/gen/schemas/')) return false;
  if (
    lower === 'src-tauri/permissions/autogenerated' ||
    lower.startsWith('src-tauri/permissions/autogenerated/')
  )
    return false;
  if (SOURCE_DIRECTORIES.has(parts[0])) return true;
  if (parts[0] === '.cargo')
    return (
      parts.length === 1 || (parts.length === 2 && ['config', 'config.toml'].includes(parts[1]))
    );
  return (
    parts.length === 1 &&
    (ROOT_FILES.has(lower) ||
      /^tsconfig(?:\.[a-z0-9_-]+)*\.json$/.test(lower) ||
      /^(?:vite|vitest|playwright|eslint|postcss|tailwind)\.config\.(?:[cm]?[jt]s|json)$/.test(
        lower,
      ))
  );
}

function assertPortablePath(path) {
  if (
    typeof path !== 'string' ||
    !path ||
    Buffer.from(path, 'utf8').toString('utf8') !== path ||
    // eslint-disable-next-line no-control-regex -- Reject control characters in portable manifest paths.
    /[\\:\x00-\x1f\x7f<>"|?*]/.test(path) ||
    path
      .split('/')
      .some(
        (part) =>
          !part ||
          part === '.' ||
          part === '..' ||
          /[. ]$/.test(part) ||
          /^(?:con|prn|aux|nul|com[1-9¹²³]|lpt[1-9¹²³])(?:\.|$)/i.test(part),
      )
  ) {
    throw new Error('Invalid or non-portable source manifest path.');
  }
}

function within(root, path) {
  const rel = relative(root, path);
  if (rel === '..' || rel.startsWith('..' + sep) || isAbsolute(rel))
    throw new Error('Source path is outside the root.');
}

function samePath(a, b) {
  return process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b;
}

function stamp(stat) {
  return [
    stat.dev,
    stat.ino,
    stat.mode,
    stat.nlink,
    stat.size,
    stat.mtimeNs,
    stat.ctimeNs,
    stat.birthtimeNs,
  ].join(':');
}

async function inspect(path, root) {
  const stat = await fs.lstat(path, { bigint: true });
  if (stat.isSymbolicLink()) throw new Error('Source link/reparse point is not supported.');
  if (!stat.isDirectory() && !stat.isFile())
    throw new Error('Source input must be a regular file or directory.');
  if (stat.isFile() && stat.nlink !== 1n)
    throw new Error('Hard-linked source input is not supported.');
  const real = await fs.realpath(path);
  if (root) within(root, real);
  if (!samePath(path, real)) throw new Error('Source alias/link/reparse path is not supported.');
  return { path, stat, real };
}

async function ancestors(root) {
  const nodes = [];
  for (let path = root; ; path = dirname(path)) {
    const node = await inspect(path);
    if (!node.stat.isDirectory()) throw new Error('Source root and ancestors must be directories.');
    nodes.push(node);
    if (path === dirname(path)) return nodes;
  }
}

// Node exposes junctions/symlinks but not every Windows reparse tag. This fixed
// read-only probe receives paths as data, never as PowerShell source or a script.
function assertWindowsAttributes(nodes) {
  if (process.platform !== 'win32') return;
  const paths = [...new Set(nodes.map((node) => node.path))];
  const command = [
    "$ErrorActionPreference = 'Stop'",
    '[Console]::InputEncoding = [Text.UTF8Encoding]::new($false)',
    '[Console]::OutputEncoding = [Text.UTF8Encoding]::new($false)',
    'try {',
    '$paths = @(([Console]::In.ReadToEnd() | ConvertFrom-Json))',
    'foreach ($path in $paths) {',
    'if (($path -isnot [string]) -or ![IO.Path]::IsPathRooted($path)) { throw "Invalid attribute path" }',
    'if (([IO.File]::GetAttributes($path) -band [IO.FileAttributes]::ReparsePoint) -ne 0) { throw "Source reparse point refused" }',
    '}',
    '[Console]::Out.Write("MDPLUS_SOURCE_ATTRIBUTES_OK")',
    '} catch { [Console]::Error.Write("Source attributes could not be verified"); exit 1 }',
  ].join('\n');
  const result = childProcess.spawnSync(
    join(process.env.SystemRoot || 'C:\\Windows', 'System32/WindowsPowerShell/v1.0/powershell.exe'),
    ['-NoLogo', '-NoProfile', '-NonInteractive', '-Command', command],
    {
      input: JSON.stringify(paths),
      encoding: 'utf8',
      shell: false,
      windowsHide: true,
      timeout: 20000,
      maxBuffer: 1024 * 1024,
    },
  );
  if (
    result.error ||
    result.signal ||
    result.status !== 0 ||
    result.stdout !== 'MDPLUS_SOURCE_ATTRIBUTES_OK' ||
    result.stderr
  ) {
    throw new Error('Source attributes/reparse probe failed closed (exit ' + result.status + ').');
  }
}

async function scan(root) {
  const nodes = new Map();
  const portableNames = new Set();
  async function visit(absolute, path) {
    const node = await inspect(absolute, root);
    nodes.set(path, node);
    if (path && !path.includes('/')) {
      const directoryInput =
        SOURCE_DIRECTORIES.has(path.toLowerCase()) || path.toLowerCase() === '.cargo';
      if (directoryInput !== node.stat.isDirectory())
        throw new Error('Source input has the wrong file/directory type: ' + path);
    }
    if (!node.stat.isDirectory()) return;
    const entries = await fs.readdir(absolute, { encoding: 'buffer' });
    const names = entries
      .map((entry) => new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(entry))
      .sort(comparePaths);
    for (const name of names) {
      const child = path ? path + '/' + name : name;
      if (!selected(child)) continue;
      assertPortablePath(child);
      const key = child.normalize('NFC').toLowerCase();
      if (portableNames.has(key)) throw new Error('Duplicate/case-colliding source manifest path.');
      portableNames.add(key);
      const full = join(absolute, name);
      within(root, full);
      await visit(full, child);
    }
  }
  await visit(root, '');
  return nodes;
}

async function hashFile(node, path) {
  const handle = await fs.open(
    node.path,
    constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0) | (constants.O_NONBLOCK ?? 0),
  );
  try {
    const opened = await handle.stat({ bigint: true });
    if (!opened.isFile() || stamp(opened) !== stamp(node.stat))
      throw new Error('Source changed before hashing: ' + path);
    const hash = createHash('sha256');
    const buffer = Buffer.alloc(128 * 1024);
    let bytes = 0;
    for (;;) {
      const read = await handle.read(buffer, 0, buffer.length, null);
      if (!read.bytesRead) break;
      bytes += read.bytesRead;
      if (BigInt(bytes) > opened.size || !Number.isSafeInteger(bytes))
        throw new Error('Source changed while hashing: ' + path);
      hash.update(buffer.subarray(0, read.bytesRead));
    }
    const after = await handle.stat({ bigint: true });
    if (BigInt(bytes) !== opened.size || stamp(after) !== stamp(opened))
      throw new Error('Source changed while hashing: ' + path);
    return { path, bytes, sha256: hash.digest('hex') };
  } finally {
    await handle.close();
  }
}

function digestFiles(files) {
  return sha256(POLICY + '\n' + JSON.stringify(files));
}

export async function createSourceManifest(directory) {
  if (typeof directory !== 'string' || !directory.trim())
    throw new Error('A source root is required.');
  const root = resolve(directory);
  if (root === dirname(root) || (process.platform === 'win32' && root.startsWith('\\\\')))
    throw new Error('A local non-root source directory is required.');
  const parents = await ancestors(root);
  const before = await scan(root);
  assertWindowsAttributes([...parents, ...before.values()]);
  const files = [];
  for (const path of [...before.keys()].sort(comparePaths)) {
    const node = before.get(path);
    if (node.stat.isFile()) files.push(await hashFile(node, path));
  }
  assertWindowsAttributes([...parents, ...before.values()]);
  const after = await scan(root);
  const changed =
    before.size !== after.size ||
    [...before].some(
      ([path, node]) => !after.has(path) || stamp(node.stat) !== stamp(after.get(path).stat),
    );
  const parentsAfter = await ancestors(root);
  const identity = (stat) => [stat.dev, stat.ino, stat.mode, stat.birthtimeNs].join(':');
  if (
    changed ||
    parents.some((node, index) => identity(node.stat) !== identity(parentsAfter[index].stat))
  ) {
    throw new Error('Source changed during capture; retry only after writers have stopped.');
  }
  if (!files.length) throw new Error('Source manifest must contain at least one selected file.');
  return { schema: 1, algorithm: 'sha256', policy: POLICY, files, digest: digestFiles(files) };
}

function exactKeys(value, keys) {
  return (
    value &&
    typeof value === 'object' &&
    !Array.isArray(value) &&
    [Object.prototype, null].includes(Object.getPrototypeOf(value)) &&
    Reflect.ownKeys(value).length === keys.length &&
    keys.every(
      (key) => Object.hasOwn(value, key) && 'value' in Object.getOwnPropertyDescriptor(value, key),
    )
  );
}

function validateManifest(manifest) {
  if (
    !exactKeys(manifest, ['schema', 'algorithm', 'policy', 'files', 'digest']) ||
    manifest.schema !== 1 ||
    manifest.algorithm !== 'sha256' ||
    manifest.policy !== POLICY ||
    !Array.isArray(manifest.files) ||
    !manifest.files.length ||
    typeof manifest.digest !== 'string' ||
    !/^[a-f0-9]{64}$/.test(manifest.digest)
  ) {
    throw new Error('Invalid source manifest schema, policy or digest.');
  }
  const names = new Set();
  let previous = null;
  const files = Array.from(manifest.files, (file) => {
    if (
      !exactKeys(file, ['path', 'bytes', 'sha256']) ||
      !Number.isSafeInteger(file.bytes) ||
      file.bytes < 0 ||
      Object.is(file.bytes, -0) ||
      typeof file.sha256 !== 'string' ||
      !/^[a-f0-9]{64}$/.test(file.sha256)
    ) {
      throw new Error('Invalid source manifest file record.');
    }
    assertPortablePath(file.path);
    if (
      !selected(file.path) ||
      SOURCE_DIRECTORIES.has(file.path.toLowerCase()) ||
      file.path.toLowerCase() === '.cargo'
    ) {
      throw new Error('Source manifest file path is outside the input policy.');
    }
    const key = file.path.normalize('NFC').toLowerCase();
    if (names.has(key)) throw new Error('Duplicate source manifest path.');
    if (previous !== null && comparePaths(previous, file.path) >= 0)
      throw new Error('Source manifest files are not in byte order.');
    names.add(key);
    previous = file.path;
    return { path: file.path, bytes: file.bytes, sha256: file.sha256 };
  });
  for (const key of names) {
    const parts = key.split('/');
    for (let length = 1; length < parts.length; length++) {
      if (names.has(parts.slice(0, length).join('/')))
        throw new Error('Source manifest file path is also a directory.');
    }
  }
  if (digestFiles(files) !== manifest.digest) throw new Error('Source manifest digest mismatch.');
  return { schema: 1, algorithm: 'sha256', policy: POLICY, files, digest: manifest.digest };
}

export function bindSource(mode, ...snapshots) {
  if (mode === 'Existing') return { status: 'unknown', manifest: null };
  if (mode !== 'Build') throw new Error('Unknown source binding mode.');
  if (snapshots.length < 2)
    throw new Error('Build binding requires at least two source manifests.');
  const manifests = snapshots.map(validateManifest);
  if (manifests.some((manifest) => manifest.digest !== manifests[0].digest))
    throw new Error('Source changed between checks/build captures.');
  return { status: 'observed-stable', manifest: manifests[0] };
}

function parseManifestJson(text) {
  const value = JSON.parse(text);
  // JSON.parse discards duplicate keys. Reject them before different consumers can disagree.
  const stack = [];
  for (const match of text.matchAll(/"(?:\\.|[^"\\])*"|[{}[\],:]/g)) {
    const token = match[0];
    if (token === '{') stack.push({ keys: new Set(), expectingKey: true });
    else if (token === '[') stack.push({ keys: null });
    else if (token === '}' || token === ']') stack.pop();
    else {
      const object = stack[stack.length - 1];
      if (token === ',' && object?.keys) object.expectingKey = true;
      else if (token.startsWith('"') && object?.keys && object.expectingKey) {
        const key = JSON.parse(token);
        if (object.keys.has(key)) throw new Error('Duplicate JSON key.');
        object.keys.add(key);
        object.expectingKey = false;
      }
    }
  }
  return value;
}

async function readManifests(paths) {
  const nodes = [];
  const parents = [];
  for (const path of paths) {
    const absolute = resolve(path);
    parents.push(...(await ancestors(dirname(absolute))));
    const node = await inspect(absolute);
    if (!node.stat.isFile() || node.stat.size > 16n * 1024n * 1024n)
      throw new Error('Invalid source manifest file size/type.');
    nodes.push(node);
  }
  assertWindowsAttributes([...parents, ...nodes]);
  const manifests = [];
  for (const node of nodes) {
    const handle = await fs.open(
      node.path,
      constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0) | (constants.O_NONBLOCK ?? 0),
    );
    try {
      if (stamp(await handle.stat({ bigint: true })) !== stamp(node.stat))
        throw new Error('Source manifest changed before reading.');
      const buffer = Buffer.alloc(Number(node.stat.size) + 1);
      let length = 0;
      while (length < buffer.length) {
        const read = await handle.read(buffer, length, buffer.length - length, null);
        if (!read.bytesRead) break;
        length += read.bytesRead;
      }
      const bytes = buffer.subarray(0, length);
      if (
        BigInt(bytes.length) !== node.stat.size ||
        stamp(await handle.stat({ bigint: true })) !== stamp(node.stat)
      ) {
        throw new Error('Source manifest changed while reading.');
      }
      try {
        manifests.push(parseManifestJson(new TextDecoder('utf-8', { fatal: true }).decode(bytes)));
      } catch {
        throw new Error('Invalid source manifest JSON.');
      }
    } finally {
      await handle.close();
    }
  }
  assertWindowsAttributes([...parents, ...nodes]);
  for (const node of nodes) {
    if (stamp((await inspect(node.path)).stat) !== stamp(node.stat))
      throw new Error('Source manifest changed during reading.');
  }
  return manifests;
}

async function cli(args) {
  if (args[0] === 'capture' && args.length === 2) return createSourceManifest(args[1]);
  if (args[0] === 'bind' && args[1] === 'Existing' && args.length === 2)
    return bindSource('Existing');
  if (args[0] === 'bind' && args[1] === 'Build' && args.length >= 4) {
    return bindSource('Build', ...(await readManifests(args.slice(2))));
  }
  throw new Error(
    'Usage: source-manifest.mjs capture <root> | bind Build <before.json> <after.json> [after-build.json] | bind Existing',
  );
}

if (process.argv[1] && samePath(resolve(process.argv[1]), fileURLToPath(import.meta.url))) {
  try {
    process.stdout.write(JSON.stringify(await cli(process.argv.slice(2))) + '\n');
  } catch (error) {
    process.stderr.write('Source manifest: ' + error.message + '\n');
    process.exitCode = 1;
  }
}
